"""Generate src/rich-cpp/core/EmojiTable.h from Python Rich's EMOJI dict.

Regenerate after upgrading the vendored/installed `rich` (dev-time only; the
C++ library itself stays zero-dependency):

    .venv/Scripts/python.exe src/rich-cpp/scripts/emoji_gen.py

The table is sorted by shortcode so lookups can binary-search. Emoji values
are emitted with 3-digit octal escapes per UTF-8 byte so the header compiles
identically under any MSVC source encoding.
"""
import sys
from pathlib import Path

from rich._emoji_codes import EMOJI

OUT = Path(__file__).resolve().parents[2] / "rich-cpp" / "core" / "EmojiTable.h"


def octal_utf8(s: str) -> str:
    return "".join(f"\\{b:03o}" for b in s.encode("utf-8"))


def main() -> None:
    items = sorted(EMOJI.items())
    lines = [
        "// Generated by src/rich-cpp/scripts/emoji_gen.py - do not edit.",
        f"// Source: Python Rich rich._emoji_codes.EMOJI ({len(items)} entries).",
        "#pragma once",
        "#include <array>",
        "#include <cstddef>",
        "",
        "namespace rich::emoji {",
        "",
        "struct EmojiEntry {",
        "    const char* name;",
        "    const char* value;",
        "};",
        "",
        f"inline constexpr std::size_t kEmojiCount = {len(items)};",
        "",
        "// Sorted by name (binary-search order). Values are octal-escaped UTF-8.",
        "inline constexpr std::array<EmojiEntry, kEmojiCount> kEmojiTable = {{",
    ]
    for name, value in items:
        name_lit = "".join(c if c.isascii() and c != '"' and c != "\\" else octal_utf8(c) for c in name)
        lines.append(
            '    {{"{name}", "{val}"}},'.format(name=name_lit, val=octal_utf8(value))
        )
    lines += ["}};", "", "} // namespace rich::emoji", ""]
    OUT.write_text("\n".join(lines), encoding="ascii")
    print(f"wrote {OUT} ({len(items)} entries)")


if __name__ == "__main__":
    main()
