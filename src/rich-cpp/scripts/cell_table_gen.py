"""Generate src/rich-cpp/unicode/CellTable.h from Python Rich's unicode data.

Regenerate after upgrading the vendored/installed `rich` (dev-time only; the
C++ library itself stays zero-dependency):

    .venv/Scripts/python.exe src/rich-cpp/scripts/cell_table_gen.py

Emits the width ranges (start, end, width) and the narrow-to-wide
codepoint set (private-use/emoji presentation, U+FE0F handling) exactly as
rich._unicode_data.load("auto") provides them, so the C++ port of
rich.cells produces identical cell lengths.
"""
from pathlib import Path

from rich._unicode_data import load

OUT = Path(__file__).resolve().parents[2] / "rich-cpp" / "unicode" / "CellTable.h"


def main() -> None:
    table = load("auto")
    widths = table.widths
    n2w = sorted(ord(c) for c in table.narrow_to_wide)
    lines = [
        "// Generated by src/rich-cpp/scripts/cell_table_gen.py - do not edit.",
        f"// Source: rich._unicode_data.load(\"auto\") (Unicode {table.unicode_version}).",
        "#pragma once",
        "#include <array>",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace rich::unicode {",
        "",
        "struct WidthRange {",
        "    uint32_t start;",
        "    uint32_t end;",
        "    uint8_t width;",
        "};",
        "",
        f"inline constexpr char kCellTableVersion[] = \"{table.unicode_version}\";",
        "",
        f"inline constexpr std::size_t kWidthRangeCount = {len(widths)};",
        "// Sorted by start; binary-searchable.",
        "inline constexpr std::array<WidthRange, kWidthRangeCount> kWidthRanges = {{",
    ]
    for start, end, width in widths:
        lines.append(f"    {{{start}, {end}, {width}}},")
    lines += [
        "}};",
        "",
        f"inline constexpr std::size_t kNarrowToWideCount = {len(n2w)};",
        "// Codepoints that render 1 cell when unqualified but 2 cells when",
        "// followed by U+FE0F (Python cell_table.narrow_to_wide). Sorted.",
        "inline constexpr std::array<uint32_t, kNarrowToWideCount> kNarrowToWide = {{",
    ]
    for i in range(0, len(n2w), 8):
        chunk = ", ".join(str(cp) for cp in n2w[i : i + 8])
        lines.append(f"    {chunk},")
    lines += ["}};", "", "} // namespace rich::unicode", ""]
    OUT.write_text("\n".join(lines), encoding="ascii")
    print(f"wrote {OUT} ({len(widths)} ranges, {len(n2w)} narrow-to-wide)")


if __name__ == "__main__":
    main()
